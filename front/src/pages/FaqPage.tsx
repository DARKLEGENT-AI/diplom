const FaqPage = () => {
  const [openIndex, setOpenIndex] = useState<number | null>(0)
  const [role, setRole] = useState('patient')

  useEffect(() => {
    const loadProfile = async () => {
      try {
        const profile = await getMe()
        setRole(profile.role || 'patient')
      } catch (error: any) {
        const message = error?.response?.data?.message || error?.message
        if (message) toast.error(Array.isArray(message) ? message.join(', ') : message)
      }
    }
    loadProfile()
  }, [])

  const faqItems = useMemo(() => {
    const roleItems = role === 'doctor' ? doctorFaq : patientFaq
    return [...roleItems, ...commonFaq]
  }, [role])

  const intro = role === 'doctor'
    ? 'Ответы для врача: расписание, окна приема, редактирование записей и профиль специалиста.'
    : 'Ответы для пациента: запись к врачу, свои приемы, профиль и обращение в поддержку.'

  return (
    <div className="mx-auto max-w-5xl space-y-6">
      <section className="rounded-lg border border-[#e5e7eb] bg-white p-6 shadow-sm">
        <p className="text-xs uppercase tracking-[0.28em] text-[#4b5563]">Справочный центр</p>
        <h2 className="mt-2 text-3xl font-semibold">Частые вопросы</h2>
        <p className="mt-3 max-w-3xl text-sm leading-6 text-[#4b5563]">{intro}</p>
      </section>

      <section className="grid gap-4 md:grid-cols-3">
        {[
          { title: 'Приемы', text: role === 'doctor' ? 'Открытие, перенос и отмена окон приема.' : 'Выбор врача, дня и свободного времени.' },
          { title: 'Профиль', text: role === 'doctor' ? 'ФИО, специальность, кабинет и описание врача.' : 'Город, аватар и данные учетной записи.' },
          { title: 'Поддержка', text: 'Чат и форма обращения для вопросов по работе системы.' },
        ].map((item) => (
          <div key={item.title} className="rounded-lg border border-[#e5e7eb] bg-white p-4">
            <p className="font-semibold text-[#1f1f1f]">{item.title}</p>
            <p className="mt-2 text-sm leading-5 text-[#4b5563]">{item.text}</p>
          </div>
        ))}
      </section>

      <section className="rounded-lg border border-[#e5e7eb] bg-white p-6 shadow-sm">
        <div className="space-y-3">
          {faqItems.map((item, index) => {
            const isOpen = openIndex === index
            return (
              <button
                type="button"
                key={item.question}
                onClick={() => setOpenIndex(isOpen ? null : index)}
                className="w-full rounded-lg border border-[#e5e7eb] bg-white p-4 text-left transition hover:border-[#dc2626]"
              >
                <div className="flex items-center justify-between gap-4">
                  <p className="text-sm font-semibold text-[#1f1f1f]">{item.question}</p>
                  <span className="text-lg text-[#4b5563]">{isOpen ? '-' : '+'}</span>
                </div>
                {isOpen && <p className="mt-3 text-sm leading-6 text-[#4b5563]">{item.answer}</p>}
              </button>
            )
          })}
        </div>
      </section>
    </div>
  )
}

export default FaqPage
